// Unit tests of sf planner waiting (SF-245), the planning copy's hook: when a Stop stays silent, how
// the user's last message is found in the transcript, and the one notification it sends.
import assert from 'node:assert/strict';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Readable } from 'node:stream';
import { after, before, test } from 'node:test';
import type { ChannelResult, Notification, NotifyConfig } from '../src/notify.js';
import { lastPromptAge, plannerWaiting, QUICK_SECONDS, silence } from '../src/planner-waiting.js';
import { type NotifyMode, saveRegistry } from '../src/registry.js';

const NOW = new Date('2026-11-16T12:00:00.000Z');
const SESSION = 'session_01Ab';

let temp: string;

before(async () => {
  temp = await mkdtemp(join(tmpdir(), 'sf-planner-waiting-'));
});

after(async () => {
  await rm(temp, { recursive: true, force: true });
});

// The ISO timestamp seconds before NOW.
const ago = (seconds: number): string => new Date(NOW.getTime() - seconds * 1000).toISOString();

const prompt = (seconds: number, content: unknown = 'Plan SF-1', extra: Record<string, unknown> = {}): Record<string, unknown> =>
  ({ type: 'user', timestamp: ago(seconds), message: { role: 'user', content }, ...extra });
const answer = (seconds: number): Record<string, unknown> =>
  ({ type: 'assistant', timestamp: ago(seconds), message: { role: 'assistant', content: [{ type: 'text', text: 'Done.' }] } });

// A transcript file of the given entries (a string is written as it is, a broken line).
async function transcript(name: string, entries: Array<Record<string, unknown> | string>): Promise<string> {
  const path = join(temp, `${name}.jsonl`);
  await writeFile(path, `${entries.map((entry) => (typeof entry === 'string' ? entry : JSON.stringify(entry))).join('\n')}\n`);
  return path;
}

test('PW-1: silence is background for running sub-agents or crons, live for an answer younger than 45 s, else undefined', () => {
  assert.equal(QUICK_SECONDS, 45);
  assert.equal(silence({ background_tasks: [{ id: 'a' }] }, undefined), 'background');
  assert.equal(silence({ session_crons: [{ id: 'c' }] }, 600), 'background');
  assert.equal(silence({ background_tasks: [{ id: 'a' }] }, 3), 'background');
  assert.equal(silence({ background_tasks: [], session_crons: [] }, 44.9), 'live');
  assert.equal(silence({}, 0), 'live');
  assert.equal(silence({}, 45), undefined);
  assert.equal(silence({ background_tasks: [], session_crons: [] }, 600), undefined);
  assert.equal(silence({}, undefined), undefined);
  // Not an array: nothing runs.
  assert.equal(silence({ background_tasks: 'x', session_crons: { a: 1 } }, undefined), undefined);
});

test("PW-2: lastPromptAge takes the user's last own message, skipping tool results, meta, sidechain entries and broken lines", async () => {
  const path = await transcript('own', [
    prompt(600),
    answer(590),
    prompt(120, [{ type: 'text', text: 'And SF-2' }, { type: 'image', source: {} }]),
    answer(110),
    prompt(60, [{ type: 'tool_result', tool_use_id: 't1', content: 'output' }]),
    prompt(30, 'Caveat: the messages below were generated by the user while running local commands.', { isMeta: true }),
    prompt(20, 'A sub-agent\'s prompt', { isSidechain: true }),
    '{"type":"user","timestamp":"broken',
    answer(5),
  ]);
  assert.equal(await lastPromptAge(path, NOW), 120);
  // A message as a string.
  assert.equal(await lastPromptAge(await transcript('string', [prompt(600), answer(500), prompt(30), answer(1)]), NOW), 30);
  // None at all, a missing file, an invalid timestamp: undefined.
  assert.equal(await lastPromptAge(await transcript('none', [answer(5), prompt(4, [{ type: 'tool_result', content: 'x' }])]), NOW), undefined);
  assert.equal(await lastPromptAge(join(temp, 'missing.jsonl'), NOW), undefined);
  assert.equal(await lastPromptAge(await transcript('invalid', [prompt(600), { ...prompt(10), timestamp: 'yesterday' }]), NOW), undefined);
});

test("lastPromptAge reads the transcript's last 400 000 bytes only", async () => {
  const filler = Array.from({ length: 450 }, () => answer(100)).map((entry) => ({ ...entry, padding: 'x'.repeat(1000) }));
  assert.equal(await lastPromptAge(await transcript('long', [prompt(300), ...filler]), NOW), undefined);
  assert.equal(await lastPromptAge(await transcript('long-recent', [prompt(300), ...filler, prompt(200)]), NOW), 200);
});

// The deps of a run: stdin from the event, a send that records the notification.
function run(event: unknown, options: { configDir?: string; env?: NodeJS.ProcessEnv; results?: ChannelResult[] } = {}): {
  sent: Array<{ notification: Notification; config: NotifyConfig }>;
  deps: Parameters<typeof plannerWaiting>[2];
} {
  const sent: Array<{ notification: Notification; config: NotifyConfig }> = [];
  const input = typeof event === 'string' ? event : JSON.stringify(event);
  return {
    sent,
    deps: {
      env: options.env ?? { CLAUDE_CODE_BRIDGE_SESSION_ID: SESSION, SF_NTFY_URL: 'http://127.0.0.1:9/topic', SF_DESKTOP_NOTIFY: 'off' },
      configDir: options.configDir ?? join(temp, 'no-config'),
      stdin: Readable.from([Buffer.from(input)]),
      now: () => NOW,
      send: async (notification, config) => {
        sent.push({ notification, config });
        return options.results ?? [];
      },
    },
  };
}

// The lines console.error writes while fn runs.
async function stderrOf(fn: () => Promise<void>): Promise<string[]> {
  const lines: string[] = [];
  const original = console.error;
  console.error = (...args: unknown[]) => lines.push(args.map(String).join(' '));
  try {
    await fn();
  } finally {
    console.error = original;
  }
  return lines;
}

test('PW-3: a Stop the user did not answer within 45 s sends "Planner waits for you", linked to the session; a quick answer or running sub-agents send nothing', async () => {
  const stale = await transcript('stale', [prompt(120), answer(1)]);
  const waiting = run({ hook_event_name: 'Stop', transcript_path: stale, background_tasks: [], session_crons: [] });
  await plannerWaiting('app', false, waiting.deps);
  assert.equal(waiting.sent.length, 1);
  assert.deepEqual(waiting.sent[0]!.notification, {
    title: 'Planner waits for you', body: 'app', priority: 'high', tags: 'speech_balloon', click: `https://claude.ai/code/${SESSION}`,
  });
  assert.deepEqual(waiting.sent[0]!.config, { desktop: false, iterations: false, ntfyUrl: 'http://127.0.0.1:9/topic', ntfyToken: undefined });

  const quick = run({ transcript_path: await transcript('quick', [prompt(10), answer(1)]) });
  await plannerWaiting('app', false, quick.deps);
  assert.equal(quick.sent.length, 0);

  const busy = run({ transcript_path: stale, background_tasks: [{ id: 'agent-1' }] });
  await plannerWaiting('app', false, busy.deps);
  assert.equal(busy.sent.length, 0);

  // No transcript, or none to read: notified. Without a session id (or an odd one): no link.
  for (const env of [{}, { CLAUDE_CODE_BRIDGE_SESSION_ID: '../../evil' }]) {
    const unknown = run({ transcript_path: join(temp, 'gone.jsonl') }, { env });
    await plannerWaiting('app', false, unknown.deps);
    assert.deepEqual(unknown.sent.map(({ notification }) => [notification.title, 'click' in notification]), [['Planner waits for you', false]]);
  }
});

test('PW-3: a permission prompt sends "Planner waits for a permission", even within 45 s', async () => {
  const quick = await transcript('permission', [prompt(5), answer(1)]);
  const asked = run({ hook_event_name: 'Notification', notification_type: 'permission_prompt', transcript_path: quick });
  await plannerWaiting('app', true, asked.deps);
  assert.deepEqual(asked.sent.map(({ notification }) => [notification.title, notification.body, notification.click]), [
    ['Planner waits for a permission', 'app', `https://claude.ai/code/${SESSION}`],
  ]);
});

test("PW-3: the workspace's notify setting: off sends nothing, brief sends the workspace's name to ntfy and keeps the link", async () => {
  const stale = await transcript('modes', [prompt(300)]);
  const configDir = join(temp, 'config');
  const withMode = async (mode: NotifyMode): Promise<Notification[]> => {
    await saveRegistry({ workspaces: { app: { read_checkout: temp, notify: mode } } }, configDir);
    const runs = [run({ transcript_path: stale }, { configDir }), run({}, { configDir })];
    await plannerWaiting('app', false, runs[0]!.deps);
    await plannerWaiting('app', true, runs[1]!.deps);
    return runs.flatMap(({ sent }) => sent.map(({ notification }) => notification));
  };
  assert.deepEqual(await withMode('off'), []);
  const brief = await withMode('brief');
  assert.deepEqual(brief.map((notification) => [notification.title, notification.ntfyBody, notification.click]), [
    ['Planner waits for you', 'app', `https://claude.ai/code/${SESSION}`],
    ['Planner waits for a permission', 'app', `https://claude.ai/code/${SESSION}`],
  ]);
  assert.deepEqual((await withMode('full')).map((notification) => [notification.title, notification.ntfyBody]), [
    ['Planner waits for you', undefined], ['Planner waits for a permission', undefined],
  ]);
});

test('PW-5: invalid stdin is an event with no fields, a failed channel and a failed send are one stderr line each, never a rejection', async () => {
  for (const input of ['not json', '[1, 2]', '', 'x'.repeat(1024 * 1024 + 1)]) {
    const invalid = run(input);
    await plannerWaiting('app', false, invalid.deps);
    assert.deepEqual(invalid.sent.map(({ notification }) => notification.title), ['Planner waits for you'], input.slice(0, 10));
  }

  const failing = run({}, { results: [{ channel: 'desktop', status: 'skipped', message: 'off' }, { channel: 'ntfy', status: 'failed', message: 'HTTP 500' }] });
  assert.deepEqual(await stderrOf(() => plannerWaiting('app', true, failing.deps)), ['sf planner waiting: ntfy failed: HTTP 500']);

  const throwing = run({});
  throwing.deps.send = async () => {
    throw new Error('the send\nbroke');
  };
  assert.deepEqual(await stderrOf(() => plannerWaiting('app', true, throwing.deps)), ['sf planner waiting: the send broke']);
});
